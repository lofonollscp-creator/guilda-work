-- Experimentos de la fase 1: ¿se comportan Citus + RLS + FTS + pgvector como necesita
-- Guilda Work? Cada bloque imprime su resultado; un error NO detiene el resto (el
-- informe sirve precisamente para ver cuáles fallan). Base: guilda_exp (se recrea).
\set ON_ERROR_STOP off
\pset pager off
\pset null '(nulo)'

\echo '### 1. Versiones, extensiones y nodos'
create extension if not exists citus;
create extension if not exists vector;
create extension if not exists unaccent;
create extension if not exists pg_trgm;
select version();
select citus_version();
select extname, extversion from pg_extension order by 1;
select count(*) as filas_pg_dist_node from pg_dist_node;
-- Un solo nodo: el coordinador también aloja shards.
do $$ begin
  if not exists (select 1 from pg_dist_node) then
    perform citus_set_coordinator_host('localhost', 5432);
  end if;
end $$;
select nodeid, groupid, nodename, noderole, shouldhaveshards, isactive from pg_dist_node;
select citus_set_node_property(nodename, nodeport, 'shouldhaveshards', true) from pg_dist_node where groupid = 0;
select * from citus_check_cluster_node_health();

\echo '### 2. Identidades y claves foráneas: qué combinaciones permiten distribuir'
-- Primera ejecución: una tabla con GENERATED ... AS IDENTITY y FK a una tabla de
-- referencia NO se pudo distribuir ("cannot complete operation on a table with identity
-- column"). Se prueban las variantes para ver cuál sirve al migrar el esquema.
create table tenants (id bigint primary key, nombre text not null);
select create_reference_table('tenants');
create table usuarios (id bigint generated by default as identity primary key, email text not null unique);
select create_reference_table('usuarios');
\echo '-- 2a. identity + FK a referencia en el CREATE (caso que falló)'
create table var_a (tenant_id bigint not null references tenants(id), id bigint generated by default as identity, primary key (tenant_id, id));
select create_distributed_table('var_a', 'tenant_id');
\echo '-- 2b. mismo, con citus.enable_local_reference_table_foreign_keys = off'
set citus.enable_local_reference_table_foreign_keys = off;
create table var_b (tenant_id bigint not null references tenants(id), id bigint generated by default as identity, primary key (tenant_id, id));
select create_distributed_table('var_b', 'tenant_id');
reset citus.enable_local_reference_table_foreign_keys;
\echo '-- 2c. identity SIN FK en el CREATE, se distribuye y luego se añade la FK'
create table var_c (tenant_id bigint not null, id bigint generated by default as identity, primary key (tenant_id, id));
select create_distributed_table('var_c', 'tenant_id');
alter table var_c add foreign key (tenant_id) references tenants(id);
\echo '-- 2d. bigserial con FK a referencia en el CREATE'
create table var_d (tenant_id bigint not null references tenants(id), id bigserial, primary key (tenant_id, id));
select create_distributed_table('var_d', 'tenant_id');
select table_name, citus_table_type, distribution_column from citus_tables where table_name::text like 'var_%' order by 1;
drop table var_a, var_b, var_c, var_d;

\echo '### 3. Modelo multitenant real (identity, sin FK en el CREATE; FK después)'
create table tareas (
  tenant_id bigint not null,
  id bigint generated by default as identity,
  usuario_id bigint,
  asunto text not null,
  creado_en text not null,
  primary key (tenant_id, id)
);
select create_distributed_table('tareas', 'tenant_id');
alter table tareas add foreign key (tenant_id) references tenants(id);
alter table tareas add foreign key (usuario_id) references usuarios(id);
create table tarea_checklist (
  tenant_id bigint not null,
  id bigint generated by default as identity,
  tarea_id bigint not null,
  texto text not null,
  primary key (tenant_id, id)
);
select create_distributed_table('tarea_checklist', 'tenant_id');
alter table tarea_checklist add foreign key (tenant_id, tarea_id) references tareas (tenant_id, id) on delete cascade;
create unique index tareas_unica on tareas (tenant_id, usuario_id, asunto);
insert into tenants select g, 'despacho ' || g from generate_series(1, 3) g;
insert into usuarios (email) select 'u' || g || '@ensayo.test' from generate_series(1, 6) g;
insert into tareas (tenant_id, usuario_id, asunto, creado_en)
  select (g % 3) + 1, (g % 6) + 1, 'tarea ' || g, '2026-10-23T10:00:00' from generate_series(1, 6000) g;
insert into tarea_checklist (tenant_id, tarea_id, texto)
  select tenant_id, id, 'paso 1' from tareas where id <= 300;
select count(*) as tareas, count(distinct id) as ids_distintos_globalmente from tareas;
select table_name, citus_table_type, distribution_column, colocation_id, shard_count from citus_tables order by 1;
\echo '-- 3a. con filtro de despacho: un solo shard'
explain (costs off) select * from tareas where tenant_id = 1 and id = 5;
\echo '-- 3b. sin filtro de despacho: debe repartirse por todos los shards'
explain (costs off) select * from tareas where id = 5;
\echo '-- 3c. join colocalizado dentro de un despacho'
explain (costs off) select t.asunto, c.texto from tareas t join tarea_checklist c using (tenant_id) where t.tenant_id = 1 and c.tarea_id = t.id;
\echo '-- 3d. transacción que toca dos despachos'
begin;
update tareas set asunto = asunto where tenant_id = 1;
update tareas set asunto = asunto where tenant_id = 2;
commit;
\echo '-- 3e. borrado en cascada (FK compuesta)'
delete from tareas where tenant_id = 1 and id = (select min(id) from tareas where tenant_id = 1 and id <= 300);
select count(*) as checklist_tenant1_tras_borrar from tarea_checklist where tenant_id = 1;

\echo '### 4. Tabla local del coordinador (corpus compartido) unida a una distribuida'
create table corpus_local (id bigint primary key, titulo text);
insert into corpus_local values (3, 'BOE-A-3'), (6, 'BOE-A-6');
select count(*) as filas_unidas from tareas t join corpus_local c on c.id = t.id where t.tenant_id = 1;

\echo '### 5. RLS con app.tenant_id (rol de aplicación con LOGIN y sin privilegios)'
-- Las conexiones internas de Citus usan el MISMO rol que la sesión: tiene que poder iniciar sesión.
drop role if exists app_rls;
create role app_rls login password 'ensayo-rls';
grant usage on schema public to app_rls;
grant select, insert, update, delete on all tables in schema public to app_rls;
grant usage, select on all sequences in schema public to app_rls;
alter table tareas enable row level security;
create policy aislamiento on tareas
  using (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
  with check (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);
set role app_rls;
\echo '-- 5a. sin contexto: no debe ver nada'
select count(*) as filas_visibles_sin_contexto from tareas;
\echo '-- 5b. con SET LOCAL app.tenant_id = 1: solo el despacho 1'
begin;
set local app.tenant_id = '1';
select count(*) as filas, min(tenant_id) as min_t, max(tenant_id) as max_t from tareas;
\echo '-- 5c. ¿poda shards solo con la política (sin filtro explícito)?'
explain (costs off) select * from tareas where id = 5;
\echo '-- 5d. con filtro explícito además de la política'
explain (costs off) select * from tareas where tenant_id = 1 and id = 5;
\echo '-- 5e. escribir en otro despacho debe fallar'
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (2, 1, 'intruso', 'x');
\echo '-- 5f. escribir en el propio despacho funciona'
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (1, 1, 'propio', 'x');
rollback;
\echo '-- 5g. SET de sesión (sin LOCAL) también llega a los shards'
set app.tenant_id = '2';
select count(*) as filas, min(tenant_id) as min_t, max(tenant_id) as max_t from tareas;
\echo '-- 5h. cambiar de contexto en la misma sesión'
set app.tenant_id = '3';
select count(*) as filas, min(tenant_id) as min_t, max(tenant_id) as max_t from tareas;
reset app.tenant_id;
reset role;

\echo '### 6. Búsqueda de texto en español (tsvector + unaccent) sobre tabla distribuida'
create function f_unaccent(text) returns text language sql immutable parallel safe strict
  as $$ select public.unaccent('public.unaccent'::regdictionary, $1) $$;
create table normas (
  tenant_id bigint not null,
  id bigint generated by default as identity,
  titulo text,
  texto text,
  tsv tsvector generated always as (to_tsvector('spanish', f_unaccent(coalesce(titulo, '') || ' ' || coalesce(texto, '')))) stored,
  primary key (tenant_id, id)
);
select create_distributed_table('normas', 'tenant_id');
create index normas_tsv on normas using gin (tsv);
insert into normas (tenant_id, titulo, texto) values
  (1, 'Ley de Enjuiciamiento', 'La jurisdicción competente conocerá de las demandas presentadas'),
  (1, 'Impuesto sobre Sociedades', 'El período impositivo coincidirá con el ejercicio económico'),
  (2, 'Estatuto de los Trabajadores', 'Los trabajadores tienen derecho a vacaciones retribuidas');
select id, titulo, round(ts_rank_cd(tsv, q)::numeric, 3) as rank
  from normas, websearch_to_tsquery('spanish', f_unaccent('jurisdiccion')) q
  where tenant_id = 1 and tsv @@ q order by rank desc;
select id, titulo from normas, websearch_to_tsquery('spanish', f_unaccent('periodo impositivo')) q where tenant_id = 1 and tsv @@ q;
select id, titulo from normas, websearch_to_tsquery('spanish', f_unaccent('vacaciones')) q where tsv @@ q;

\echo '### 7. pgvector sobre tabla distribuida (HNSW)'
create table emb (
  tenant_id bigint not null,
  id bigint generated by default as identity,
  v vector(3),
  primary key (tenant_id, id)
);
select create_distributed_table('emb', 'tenant_id');
create index emb_v on emb using hnsw (v vector_cosine_ops);
insert into emb (tenant_id, v)
  select (g % 3) + 1, ('[' || random() || ',' || random() || ',' || random() || ']')::vector from generate_series(1, 300) g;
select id, round((v <=> '[0.1,0.2,0.3]')::numeric, 4) as distancia from emb where tenant_id = 1 order by v <=> '[0.1,0.2,0.3]' limit 3;

\echo '### 8. Trigger de auditoría inmutable sobre tabla distribuida'
create table auditoria (
  tenant_id bigint not null,
  id bigint generated by default as identity,
  evento text,
  primary key (tenant_id, id)
);
select create_distributed_table('auditoria', 'tenant_id');
create function auditoria_inmutable() returns trigger language plpgsql
  as $$ begin raise exception 'auditoria inmutable'; end $$;
create trigger auditoria_sin_modificar before update or delete on auditoria
  for each row execute function auditoria_inmutable();
select tgname, tgrelid::regclass from pg_trigger where not tgisinternal and tgrelid::regclass::text = 'auditoria';
insert into auditoria (tenant_id, evento) values (1, 'a');
update auditoria set evento = 'b' where tenant_id = 1;
delete from auditoria where tenant_id = 1;
select count(*) as filas_auditoria_deben_ser_1 from auditoria;
\echo '-- ¿el trigger existe también en los shards (si no, un UPDATE directo al shard lo saltaría)?'
select count(*) as triggers_en_shards from run_command_on_shards('auditoria', $cmd$select count(*)::text from pg_trigger where tgrelid = '%s'::regclass and not tgisinternal$cmd$) where result::int > 0;
\echo '-- el rol de aplicación tampoco puede saltárselo con TRUNCATE'
set role app_rls;
truncate auditoria;
reset role;
select count(*) as filas_auditoria_tras_truncate from auditoria;

\echo '### 9. Coste de distribuir muchas tablas (esquema de ~190 tablas)'
\timing on
do $$
declare i int;
begin
  for i in 1..190 loop
    execute format('create table sim_%s (tenant_id bigint not null, id bigint generated by default as identity, dato text, primary key (tenant_id, id))', i);
    perform create_distributed_table(format('sim_%s', i), 'tenant_id');
  end loop;
end $$;
\timing off
select count(*) as tablas_sim, (select count(*) from citus_shards) as shards_totales from citus_tables where table_name::text like 'sim_%';

\echo '### 10. Resumen'
select (select count(*) from citus_shards) as shards, pg_size_pretty(pg_database_size(current_database())) as tamano_bd;

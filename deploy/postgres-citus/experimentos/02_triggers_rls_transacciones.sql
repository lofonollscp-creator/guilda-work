-- Segunda tanda (se ejecuta tras 01, en la misma base): triggers, RLS dentro de
-- transacciones, propagación del contexto de despacho y coste de shards.
\set ON_ERROR_STOP off
\pset pager off
\pset null '(nulo)'

\echo '### A. Triggers sobre tablas distribuidas'
create function aud_inmutable() returns trigger language plpgsql
  as $$ begin raise exception 'auditoria inmutable'; end $$;
\echo '-- A1. sin citus.enable_unsafe_triggers'
create table aud1 (tenant_id bigint not null, id bigint generated by default as identity, evento text, primary key (tenant_id, id));
select create_distributed_table('aud1', 'tenant_id');
create trigger t_aud before update or delete on aud1 for each row execute function aud_inmutable();
\echo '-- A2. con citus.enable_unsafe_triggers = on (ANTES de crear el trigger)'
set citus.enable_unsafe_triggers = on;
create table aud2 (tenant_id bigint not null, id bigint generated by default as identity, evento text, primary key (tenant_id, id));
select create_distributed_table('aud2', 'tenant_id');
create trigger t_aud before update or delete on aud2 for each row execute function aud_inmutable();
select 'aud1' as tabla, count(*) as triggers_en_coordinador from pg_trigger where tgrelid = 'aud1'::regclass and not tgisinternal
union all select 'aud2', count(*) from pg_trigger where tgrelid = 'aud2'::regclass and not tgisinternal;
select count(*) as shards_de_aud2_con_trigger from run_command_on_shards('aud2', $cmd$select count(*)::text from pg_trigger where tgrelid = '%s'::regclass and not tgisinternal$cmd$) where result::int > 0;
insert into aud2 (tenant_id, evento) values (1, 'a');
update aud2 set evento = 'b' where tenant_id = 1;
delete from aud2 where tenant_id = 1;
select count(*) as filas_aud2_deben_ser_1 from aud2;
reset citus.enable_unsafe_triggers;
\echo '-- A2b. con el GUC apagado de nuevo, ¿el trigger sigue protegiendo en ejecución?'
update aud2 set evento = 'c' where tenant_id = 1;
delete from aud2 where tenant_id = 1;
select count(*) as filas_aud2_deben_seguir_1 from aud2;
\echo '-- A2c. patrón de historial: un trigger escribe en OTRA tabla distribuida colocalizada (mismo tenant_id)'
set citus.enable_unsafe_triggers = on;
create table doc (tenant_id bigint not null, id bigint generated by default as identity, texto text, primary key (tenant_id, id));
create table doc_historial (tenant_id bigint not null, id bigint generated by default as identity, doc_id bigint, accion text, primary key (tenant_id, id));
select create_distributed_table('doc', 'tenant_id');
select create_distributed_table('doc_historial', 'tenant_id', colocate_with := 'doc');
create function doc_historial_fn() returns trigger language plpgsql as $$
begin insert into doc_historial (tenant_id, doc_id, accion) values (coalesce(new.tenant_id, old.tenant_id), coalesce(new.id, old.id), tg_op); return coalesce(new, old); end $$;
create trigger t_doc after insert or update or delete on doc for each row execute function doc_historial_fn();
insert into doc (tenant_id, texto) values (1, 'uno'), (2, 'dos');
update doc set texto = 'uno-bis' where tenant_id = 1;
delete from doc where tenant_id = 2;
select tenant_id, accion, count(*) from doc_historial group by 1, 2 order by 1, 2;
reset citus.enable_unsafe_triggers;
\echo '-- A2d. lo mismo SIN el GUC en ejecución (¿se necesita al disparar?)'
insert into doc (tenant_id, texto) values (3, 'tres');
select tenant_id, accion, count(*) from doc_historial where tenant_id = 3 group by 1, 2;
\echo '-- A3. inmutabilidad por PERMISOS (sin trigger): el rol de aplicación solo puede insertar y leer'
create table aud3 (tenant_id bigint not null, id bigint generated by default as identity, evento text, primary key (tenant_id, id));
select create_distributed_table('aud3', 'tenant_id');
revoke all on aud3 from app_rls;
grant select, insert on aud3 to app_rls;
grant usage, select on all sequences in schema public to app_rls;
set role app_rls;
insert into aud3 (tenant_id, evento) values (1, 'a');
update aud3 set evento = 'b' where tenant_id = 1;
delete from aud3 where tenant_id = 1;
truncate aud3;
select count(*) as filas_aud3_deben_ser_1 from aud3;
reset role;

\echo '### B. RLS dentro de transacciones (usuario de aplicación, rol con LOGIN)'
set role app_rls;
\echo '-- B1. SELECT repartido y después INSERT propio en la misma transacción'
begin;
set local app.tenant_id = '1';
select count(*) as filas from tareas;
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (1, 1, 'b1', 'x');
commit;
\echo '-- B2. INSERT en otro despacho, solo (debe violar la política)'
begin;
set local app.tenant_id = '1';
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (2, 1, 'intruso', 'x');
rollback;
\echo '-- B3. SELECT filtrado, INSERT propio y UPDATE propio'
begin;
set local app.tenant_id = '1';
select count(*) as filas from tareas where tenant_id = 1;
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (1, 1, 'b3', 'x');
update tareas set asunto = 'b3-bis' where tenant_id = 1 and asunto = 'b3';
commit;
\echo '-- B4. UPDATE sobre otro despacho: debe afectar a 0 filas'
begin;
set local app.tenant_id = '1';
update tareas set asunto = 'hack' where tenant_id = 2;
rollback;
\echo '-- B6. ¿el error "cannot switch local execution status" venía de EXPLAIN dentro de la transacción?'
begin;
set local app.tenant_id = '1';
select count(*) as filas from tareas;
explain (costs off) select * from tareas where id = 5;
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (1, 1, 'b6', 'x');
rollback;
\echo '-- B5. tras el COMMIT el contexto desaparece (SET LOCAL): no ve nada'
select count(*) as filas_sin_contexto from tareas;
reset role;

\echo '### C. Simulación de varios nodos: sin ejecución local y con propagación de SET'
set role app_rls;
set citus.enable_local_execution = off;
set citus.propagate_set_commands = 'none';
\echo '-- C1. propagate_set_commands = none + SET LOCAL'
begin; set local app.tenant_id = '1'; select count(*) as filas from tareas where id > 0; rollback;
\echo '-- C2. propagate_set_commands = local + SET LOCAL'
set citus.propagate_set_commands = 'local';
begin; set local app.tenant_id = '1'; select count(*) as filas from tareas where id > 0; rollback;
\echo '-- C3. propagate_set_commands = local + SET de sesión (sin LOCAL)'
set app.tenant_id = '2';
select count(*) as filas from tareas where id > 0;
reset app.tenant_id;
\echo '-- C4. escritura con contexto propagado'
begin; set local app.tenant_id = '1';
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (1, 1, 'c4', 'x');
insert into tareas (tenant_id, usuario_id, asunto, creado_en) values (2, 1, 'c4-intruso', 'x');
rollback;
reset citus.propagate_set_commands;
reset citus.enable_local_execution;
reset role;

\echo '### D. Coste de shards: 190 tablas con 8 y con 16 shards (frente a 32 en el punto 9 de 01)'
select pg_database_size(current_database()) as bytes_antes \gset
\timing on
do $$
declare i int;
begin
  for i in 1..190 loop
    execute format('create table s8_%s (tenant_id bigint not null, id bigint generated by default as identity, dato text, primary key (tenant_id, id))', i);
    if i = 1 then perform create_distributed_table('s8_1', 'tenant_id', shard_count := 8); else perform create_distributed_table(format('s8_%s', i), 'tenant_id', colocate_with := 's8_1'); end if;
  end loop;
end $$;
\timing off
select pg_size_pretty(pg_database_size(current_database()) - :bytes_antes) as crecimiento_8_shards;
select pg_database_size(current_database()) as bytes_antes \gset
\timing on
do $$
declare i int;
begin
  for i in 1..190 loop
    execute format('create table s16_%s (tenant_id bigint not null, id bigint generated by default as identity, dato text, primary key (tenant_id, id))', i);
    if i = 1 then perform create_distributed_table('s16_1', 'tenant_id', shard_count := 16); else perform create_distributed_table(format('s16_%s', i), 'tenant_id', colocate_with := 's16_1'); end if;
  end loop;
end $$;
\timing off
select pg_size_pretty(pg_database_size(current_database()) - :bytes_antes) as crecimiento_16_shards;
select count(*) as shards_totales from citus_shards;

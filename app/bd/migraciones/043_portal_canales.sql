-- SMS y WhatsApp para los avisos del portal
CREATE TABLE IF NOT EXISTS portal_canales_config (
    tenant_id bigint,
    sms_activo bigint NOT NULL DEFAULT 0,
    whatsapp_activo bigint NOT NULL DEFAULT 0,
    account_sid text NOT NULL DEFAULT '',
    remitente_sms text NOT NULL DEFAULT '',
    remitente_whatsapp text NOT NULL DEFAULT '',
    whatsapp_content_sid text NOT NULL DEFAULT '',
    actualizado_en text NOT NULL,
    PRIMARY KEY (tenant_id)
);
CREATE TABLE IF NOT EXISTS portal_canales_personas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    email text NOT NULL,
    telefono text NOT NULL,
    canal text NOT NULL,
    verificado_en text,
    consentimiento_en text,
    baja_en text,
    codigo_hash text,
    codigo_vence text,
    intentos bigint NOT NULL DEFAULT 0,
    codigos_hora text,
    dia text,
    enviados_dia bigint NOT NULL DEFAULT 0,
    creado_en text NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (tenant_id, cliente_fiscal_id, email),
    CHECK (canal IN ('sms', 'whatsapp'))
);
CREATE TABLE IF NOT EXISTS portal_canales_envios (
    tenant_id bigint,
    dia text,
    canal text,
    n bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (tenant_id, dia, canal)
);

-- Rebotes de marketing, canales de envío (Brevo y Mailchimp) y su referencia en los envíos
CREATE TABLE IF NOT EXISTS marketing_rebotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    email text NOT NULL,
    envio_id bigint,
    tipo text NOT NULL,
    codigo text,
    detalle text,
    origen text NOT NULL,
    recibido_en text NOT NULL,
    PRIMARY KEY (id),
    CHECK (tipo IN ('duro', 'blando', 'queja'))
);
CREATE TABLE IF NOT EXISTS marketing_proveedores (
    tenant_id bigint,
    proveedor text,
    clave text NOT NULL,
    ajustes text NOT NULL DEFAULT '{}',
    verificado_en text,
    actualizado_en text NOT NULL,
    actualizado_por bigint,
    PRIMARY KEY (tenant_id, proveedor),
    CHECK (proveedor IN ('brevo', 'mailchimp'))
);
CREATE INDEX IF NOT EXISTS idx_marketing_rebotes ON marketing_rebotes(tenant_id, email, recibido_en);
ALTER TABLE marketing_envios ADD COLUMN IF NOT EXISTS canal text NOT NULL DEFAULT 'propio';
ALTER TABLE marketing_envios ADD COLUMN IF NOT EXISTS proveedor_ref text;
ALTER TABLE marketing_envios ADD COLUMN IF NOT EXISTS proveedor_estado text;

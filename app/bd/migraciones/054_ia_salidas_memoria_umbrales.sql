-- IA: contador de datos que salen a proveedores externos, memoria del cliente, umbrales de alertas y latencia/fallos por proveedor.
CREATE TABLE IF NOT EXISTS ia_salidas_datos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    proveedor text NOT NULL,
    modelo text NOT NULL DEFAULT '',
    tarea text NOT NULL DEFAULT '',
    protegidos text NOT NULL DEFAULT '{}',
    adjuntos bigint NOT NULL DEFAULT 0,
    creado_en text NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_ia_salidas_tenant ON ia_salidas_datos(tenant_id, creado_en);
CREATE TABLE IF NOT EXISTS cliente_memoria (
    tenant_id bigint,
    cliente_fiscal_id bigint,
    texto text NOT NULL DEFAULT '',
    borrador text NOT NULL DEFAULT '',
    borrador_en text,
    actualizado_por bigint,
    actualizado_en text,
    PRIMARY KEY (tenant_id, cliente_fiscal_id)
);
ALTER TABLE ia_config_despacho ADD COLUMN IF NOT EXISTS umbrales text NOT NULL DEFAULT '{}';
ALTER TABLE ia_uso_proveedor ADD COLUMN IF NOT EXISTS errores bigint NOT NULL DEFAULT 0;
ALTER TABLE ia_uso_proveedor ADD COLUMN IF NOT EXISTS ms_total bigint NOT NULL DEFAULT 0;

-- IA: cola de trabajos en segundo plano (leer todas las facturas, comparar modelos)
CREATE TABLE IF NOT EXISTS ia_trabajos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    usuario_id bigint,
    tipo text NOT NULL,
    referencia bigint,
    lote text NOT NULL,
    estado text NOT NULL DEFAULT 'pendiente',
    intentos bigint NOT NULL DEFAULT 0,
    error text,
    datos text,
    resultado text,
    no_antes_de text,
    creado_en text NOT NULL,
    iniciado_en text,
    terminado_en text,
    PRIMARY KEY (id),
    CHECK (estado IN ('pendiente', 'leyendo', 'hecha', 'error'))
);
CREATE INDEX IF NOT EXISTS idx_ia_trabajos_estado ON ia_trabajos(estado, no_antes_de);
CREATE INDEX IF NOT EXISTS idx_ia_trabajos_lote ON ia_trabajos(tenant_id, lote);

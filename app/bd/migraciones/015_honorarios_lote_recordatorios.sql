-- Honorarios por tramos de los vencimientos fiscales, cambios en lote de vencimientos y recordatorios de firma
CREATE TABLE IF NOT EXISTS honorarios_reglas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    nombre text NOT NULL,
    prioridad bigint NOT NULL DEFAULT 100,
    activa bigint NOT NULL DEFAULT 1,
    modelo text NOT NULL DEFAULT '',
    forma_juridica text NOT NULL DEFAULT '',
    calculo text NOT NULL,
    importe_centimos bigint NOT NULL DEFAULT 0,
    unidad_centimos bigint NOT NULL DEFAULT 0,
    minimo_centimos bigint NOT NULL DEFAULT 0,
    tramos text NOT NULL DEFAULT '[]',
    creada_por bigint,
    creada_en text NOT NULL,
    actualizada_en text,
    papelera_en text,
    PRIMARY KEY (id),
    CHECK (calculo IN ('fijo', 'por_apunte', 'tramos'))
);
CREATE TABLE IF NOT EXISTS honorarios_aplicados (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    vencimiento_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    regla_id bigint,
    regla_nombre text NOT NULL,
    concepto text NOT NULL,
    unidades bigint NOT NULL DEFAULT 0,
    importe_centimos bigint NOT NULL,
    desglose text NOT NULL DEFAULT '{}',
    estado text NOT NULL DEFAULT 'confirmado',
    confirmado_por bigint,
    confirmado_en text NOT NULL,
    facturado_en text,
    referencia_factura text,
    anulado_en text,
    anulado_motivo text,
    PRIMARY KEY (id),
    CHECK (estado IN ('confirmado', 'facturado', 'anulado'))
);
CREATE TABLE IF NOT EXISTS fiscal_acciones_masivas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    usuario_id bigint NOT NULL,
    tipo text NOT NULL,
    parametros text NOT NULL DEFAULT '{}',
    descripcion text NOT NULL,
    afectados text NOT NULL DEFAULT '[]',
    omitidos text NOT NULL DEFAULT '[]',
    estado text NOT NULL DEFAULT 'propuesta',
    creada_en text NOT NULL,
    aplicada_en text,
    deshecha_en text,
    caduca_en text,
    PRIMARY KEY (id),
    CHECK (tipo IN ('reasignar', 'posponer')),
    CHECK (estado IN ('propuesta', 'aplicada', 'deshecha', 'cancelada'))
);
CREATE INDEX IF NOT EXISTS idx_fiscal_acciones_masivas ON fiscal_acciones_masivas(tenant_id, creada_en);
CREATE INDEX IF NOT EXISTS idx_honorarios_aplicados ON honorarios_aplicados(tenant_id, vencimiento_id);
CREATE INDEX IF NOT EXISTS idx_honorarios_aplicados_cliente ON honorarios_aplicados(tenant_id, cliente_fiscal_id, estado);
CREATE INDEX IF NOT EXISTS idx_honorarios_reglas ON honorarios_reglas(tenant_id, prioridad);
ALTER TABLE documentos_firma ADD COLUMN IF NOT EXISTS recordado_en text;
ALTER TABLE documentos_firma ADD COLUMN IF NOT EXISTS recordatorios bigint NOT NULL DEFAULT 0;

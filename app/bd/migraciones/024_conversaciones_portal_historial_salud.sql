-- Portal: conversaciones libres entre el cliente y su gestoría; histórico del panel de salud
CREATE TABLE IF NOT EXISTS portal_conversaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    asunto text NOT NULL,
    peticion_id bigint,
    estado text NOT NULL DEFAULT 'abierta',
    iniciada_por text NOT NULL,
    creado_en text NOT NULL,
    actualizado_en text NOT NULL,
    cerrada_en text,
    cerrada_por bigint,
    PRIMARY KEY (id),
    CHECK (estado IN ('abierta', 'cerrada')),
    CHECK (iniciada_por IN ('cliente', 'despacho'))
);
CREATE INDEX IF NOT EXISTS idx_portal_conversaciones_cliente ON portal_conversaciones(tenant_id, cliente_fiscal_id, estado);
CREATE TABLE IF NOT EXISTS portal_conversaciones_mensajes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    conversacion_id bigint NOT NULL,
    de text NOT NULL,
    autor text NOT NULL DEFAULT '',
    texto text NOT NULL,
    creado_en text NOT NULL,
    leido_cliente bigint NOT NULL DEFAULT 0,
    leido_equipo bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CHECK (de IN ('cliente', 'despacho'))
);
CREATE INDEX IF NOT EXISTS idx_portal_conversaciones_mensajes ON portal_conversaciones_mensajes(tenant_id, conversacion_id, id);
CREATE TABLE IF NOT EXISTS salud_historial (
    clave text,
    momento text,
    estado text NOT NULL,
    valor double precision,
    detalle text,
    PRIMARY KEY (clave, momento)
);
CREATE INDEX IF NOT EXISTS idx_salud_historial_momento ON salud_historial(momento);

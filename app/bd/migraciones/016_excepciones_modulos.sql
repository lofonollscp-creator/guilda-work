-- Excepciones al plan de un despacho con motivo, caducidad e historial
CREATE TABLE IF NOT EXISTS tenants_verticales_historial (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    vertical_id text NOT NULL,
    accion text NOT NULL,
    activo_hasta text,
    motivo text NOT NULL,
    por text NOT NULL,
    creado_en text NOT NULL,
    PRIMARY KEY (id),
    CHECK (accion IN ('activar', 'desactivar', 'prueba', 'volver_al_plan'))
);
CREATE INDEX IF NOT EXISTS idx_tenants_verticales_historial ON tenants_verticales_historial(tenant_id, id);
ALTER TABLE tenants_verticales ADD COLUMN IF NOT EXISTS motivo text;
ALTER TABLE tenants_verticales ADD COLUMN IF NOT EXISTS fijado_por text;
ALTER TABLE tenants_verticales ADD COLUMN IF NOT EXISTS fijado_en text;

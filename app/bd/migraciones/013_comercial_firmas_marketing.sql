-- Documentos para firmar con Documenso, cambios en lote y marketing del Comercial
CREATE TABLE IF NOT EXISTS documentos_plantillas (
    tenant_id bigint,
    clave text,
    cuerpo text,
    ajustes text NOT NULL DEFAULT '{}',
    actualizado_en text NOT NULL,
    actualizado_por bigint,
    PRIMARY KEY (tenant_id, clave)
);
CREATE TABLE IF NOT EXISTS documentos_firma (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_id bigint NOT NULL,
    plantilla text NOT NULL,
    titulo text NOT NULL,
    datos text NOT NULL DEFAULT '{}',
    texto text NOT NULL,
    firmante_email text NOT NULL,
    firmante_nombre text NOT NULL,
    estado text NOT NULL DEFAULT 'borrador',
    documenso_id text,
    pdf_sha256 text NOT NULL,
    documento_firmado_id bigint,
    creado_por bigint,
    creado_en text NOT NULL,
    enviado_en text,
    firmado_en text,
    actualizado_en text,
    PRIMARY KEY (id),
    CHECK (estado IN ('borrador', 'enviado', 'firmado', 'rechazado', 'cancelado'))
);
CREATE TABLE IF NOT EXISTS crm_acciones_masivas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    usuario_id bigint NOT NULL,
    tipo text NOT NULL,
    parametros text NOT NULL DEFAULT '{}',
    descripcion text NOT NULL,
    afectados text NOT NULL DEFAULT '[]',
    omitidos text NOT NULL DEFAULT '[]',
    estado text NOT NULL DEFAULT 'propuesta',
    creada_en text NOT NULL,
    aplicada_en text,
    deshecha_en text,
    caduca_en text,
    PRIMARY KEY (id),
    CHECK (tipo IN ('mover_etapa', 'reasignar', 'posponer_cierre', 'papelera')),
    CHECK (estado IN ('propuesta', 'aplicada', 'deshecha', 'cancelada'))
);
CREATE TABLE IF NOT EXISTS marketing_contactos (
    tenant_id bigint,
    email text,
    nombre text,
    cliente_id bigint,
    estado text NOT NULL,
    origen text NOT NULL,
    evidencia text NOT NULL,
    documento_firma_id bigint,
    consentido_en text,
    baja_en text,
    registrado_por bigint,
    actualizado_en text NOT NULL,
    PRIMARY KEY (tenant_id, email),
    CHECK (estado IN ('consentido', 'baja', 'rebotado'))
);
CREATE TABLE IF NOT EXISTS marketing_grupos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    nombre text NOT NULL,
    descripcion text,
    reglas text NOT NULL DEFAULT '{}',
    creado_por bigint,
    creado_en text NOT NULL,
    papelera_en text,
    PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS marketing_plantillas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    nombre text NOT NULL,
    asunto text NOT NULL,
    bloques text NOT NULL DEFAULT '[]',
    creado_por bigint,
    creado_en text NOT NULL,
    actualizado_en text,
    papelera_en text,
    PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS marketing_envios (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    nombre text NOT NULL,
    grupo_id bigint,
    asunto text NOT NULL,
    bloques text NOT NULL DEFAULT '[]',
    estado text NOT NULL DEFAULT 'borrador',
    url_base text,
    programado_para text,
    total bigint NOT NULL DEFAULT 0,
    enviados bigint NOT NULL DEFAULT 0,
    errores bigint NOT NULL DEFAULT 0,
    excluidos text NOT NULL DEFAULT '{}',
    ultimo_error text,
    creado_por bigint,
    creado_en text NOT NULL,
    programado_por bigint,
    iniciado_en text,
    terminado_en text,
    PRIMARY KEY (id),
    CHECK (estado IN ('borrador', 'programado', 'enviando', 'enviado', 'cancelado'))
);
CREATE TABLE IF NOT EXISTS marketing_envio_destinatarios (
    envio_id bigint,
    tenant_id bigint NOT NULL,
    email text,
    nombre text,
    cliente_id bigint,
    estado text NOT NULL DEFAULT 'pendiente',
    enviado_en text,
    error text,
    PRIMARY KEY (envio_id, email),
    CHECK (estado IN ('pendiente', 'enviado', 'error', 'omitido'))
);
CREATE INDEX IF NOT EXISTS idx_crm_acciones_masivas ON crm_acciones_masivas(tenant_id, creada_en);
CREATE INDEX IF NOT EXISTS idx_documentos_firma_cliente ON documentos_firma(tenant_id, cliente_id, creado_en);
CREATE INDEX IF NOT EXISTS idx_marketing_envios ON marketing_envios(tenant_id, estado, creado_en);

-- Portal: centro de avisos (con lo leído por persona) y archivos adjuntos a los mensajes de las conversaciones
CREATE TABLE IF NOT EXISTS portal_novedades (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    titulo text NOT NULL,
    detalle text NOT NULL DEFAULT '',
    url text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_portal_novedades_cliente ON portal_novedades(tenant_id, cliente_fiscal_id, creado_en);
CREATE TABLE IF NOT EXISTS portal_novedades_lectura (
    tenant_id bigint,
    cliente_fiscal_id bigint,
    email text,
    leidas_hasta text NOT NULL,
    PRIMARY KEY (tenant_id, cliente_fiscal_id, email)
);
CREATE TABLE IF NOT EXISTS portal_conversaciones_adjuntos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    mensaje_id bigint NOT NULL,
    documento_id bigint NOT NULL,
    creado_en text NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_portal_conversaciones_adjuntos ON portal_conversaciones_adjuntos(tenant_id, mensaje_id);

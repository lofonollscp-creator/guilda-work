-- Inmutabilidad (solo anexado): lo exportado o presentado no se modifica. El borrado solo lo permite la purga de un despacho (el mismo permiso que usa la auditoría).
CREATE OR REPLACE FUNCTION fiscal_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' AND COALESCE((SELECT valor FROM auditoria_control WHERE clave = 'permitir_borrado'), '0') = '1' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION '% es inmutable: no se puede %.', TG_TABLE_NAME, CASE TG_OP WHEN 'UPDATE' THEN 'modificar' ELSE 'borrar' END USING ERRCODE = 'integrity_constraint_violation';
END $$;
DROP TRIGGER IF EXISTS fiscal_instantaneas_inmutable ON fiscal_instantaneas;
CREATE TRIGGER fiscal_instantaneas_inmutable BEFORE UPDATE OR DELETE ON fiscal_instantaneas FOR EACH ROW EXECUTE FUNCTION fiscal_inmutable();
DROP TRIGGER IF EXISTS fiscal_artefactos_inmutable ON fiscal_artefactos;
CREATE TRIGGER fiscal_artefactos_inmutable BEFORE UPDATE OR DELETE ON fiscal_artefactos FOR EACH ROW EXECUTE FUNCTION fiscal_inmutable();

CREATE OR REPLACE FUNCTION fiscal_casillas_solo_borrador() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE est text;
BEGIN
    IF TG_OP = 'DELETE' AND COALESCE((SELECT valor FROM auditoria_control WHERE clave = 'permitir_borrado'), '0') = '1' THEN
        RETURN OLD;
    END IF;
    SELECT estado INTO est FROM fiscal_declaraciones WHERE tenant_id = OLD.tenant_id AND id = OLD.declaracion_id;
    IF est IS NULL THEN                                         -- la declaración ya no está: es un borrado en cascada de su borrado permitido
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
    END IF;
    IF est = 'borrador' OR (TG_OP = 'DELETE' AND est = 'anulada') THEN
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
    END IF;
    RAISE EXCEPTION 'Las casillas de una declaración ya revisada, exportada o presentada no se modifican ni se borran.' USING ERRCODE = 'integrity_constraint_violation';
END $$;
DROP TRIGGER IF EXISTS fiscal_casillas_solo_borrador ON fiscal_casillas;
CREATE TRIGGER fiscal_casillas_solo_borrador BEFORE UPDATE OR DELETE ON fiscal_casillas FOR EACH ROW EXECUTE FUNCTION fiscal_casillas_solo_borrador();

CREATE OR REPLACE FUNCTION fiscal_declaraciones_reglas() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado IN ('revisada', 'exportada', 'presentada') AND COALESCE((SELECT valor FROM auditoria_control WHERE clave = 'permitir_borrado'), '0') <> '1' THEN
            RAISE EXCEPTION 'Una declaración revisada, exportada o presentada no se borra.' USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN OLD;
    END IF;
    IF NEW.estado <> OLD.estado AND NOT (
        (OLD.estado = 'borrador' AND NEW.estado IN ('revisada', 'anulada')) OR (OLD.estado = 'revisada' AND NEW.estado IN ('exportada', 'anulada')) OR (OLD.estado = 'exportada' AND NEW.estado IN ('presentada', 'anulada'))) THEN
        RAISE EXCEPTION 'Transición de estado no permitida en la declaración fiscal.' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.estado IN ('exportada', 'presentada') AND (NEW.instantanea_id <> OLD.instantanea_id OR NEW.resultado_centimos <> OLD.resultado_centimos OR NEW.tipo_declaracion <> OLD.tipo_declaracion
        OR NEW.modelo <> OLD.modelo OR NEW.ejercicio <> OLD.ejercicio OR NEW.periodo <> OLD.periodo OR NEW.version_motor <> OLD.version_motor OR NEW.version_diseno <> OLD.version_diseno) THEN
        RAISE EXCEPTION 'Una declaración exportada o presentada no se modifica: se abre una rectificación.' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS fiscal_declaraciones_reglas ON fiscal_declaraciones;
CREATE TRIGGER fiscal_declaraciones_reglas BEFORE UPDATE OR DELETE ON fiscal_declaraciones FOR EACH ROW EXECUTE FUNCTION fiscal_declaraciones_reglas();


-- Plantillas de apuntes recurrentes de Guilda Fiscal (alquileres y gastos fijos que se repiten solos)
CREATE TABLE IF NOT EXISTS fiscal_apuntes_recurrentes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    nombre text NOT NULL,
    apunte_id bigint,
    datos text NOT NULL,
    frecuencia text NOT NULL,
    generadas bigint NOT NULL DEFAULT 0,
    hasta text,
    activa bigint NOT NULL DEFAULT 1,
    ultima_ejecucion text,
    ultimo_error text,
    creado_por bigint NOT NULL,
    creado_en text NOT NULL,
    actualizado_en text,
    PRIMARY KEY (id),
    CHECK (frecuencia IN ('mensual','trimestral'))
);
CREATE INDEX IF NOT EXISTS idx_fiscal_apuntes_recurrentes ON fiscal_apuntes_recurrentes (tenant_id, cliente_fiscal_id, activa);

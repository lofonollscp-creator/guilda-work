-- Dossier de actividad del portal con validación de la gestoría
CREATE TABLE IF NOT EXISTS portal_dossiers (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    desde text NOT NULL,
    hasta text NOT NULL,
    creado_por text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    datos text NOT NULL,
    huella text NOT NULL,
    estado text NOT NULL DEFAULT 'sin_validar',
    pedido_en text,
    validado_por bigint,
    validado_en text,
    codigo text,
    nota text NOT NULL DEFAULT '',
    PRIMARY KEY (id),
    UNIQUE (tenant_id, codigo),
    CHECK (estado IN ('sin_validar', 'pendiente', 'validado', 'rechazado'))
);
CREATE INDEX IF NOT EXISTS idx_portal_dossiers_cliente ON portal_dossiers(tenant_id, cliente_fiscal_id, creado_en);
CREATE INDEX IF NOT EXISTS idx_portal_dossiers_codigo ON portal_dossiers(codigo);

-- Presupuestos y propuestas aceptables desde el portal
CREATE TABLE IF NOT EXISTS portal_propuestas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    titulo text NOT NULL,
    descripcion text NOT NULL DEFAULT '',
    lineas text NOT NULL,
    total_centimos bigint NOT NULL DEFAULT 0,
    estado text NOT NULL DEFAULT 'borrador',
    valida_hasta text,
    cobro_centimos bigint NOT NULL DEFAULT 0,
    creada_por bigint,
    creada_en text NOT NULL,
    enviada_en text,
    huella text,
    respondida_en text,
    respondida_por text,
    nombre_firmante text,
    motivo text NOT NULL DEFAULT '',
    pagado_en text,
    pagado_centimos bigint,
    stripe_session_id text,
    visto_equipo bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CHECK (estado IN ('borrador', 'enviada', 'aceptada', 'rechazada', 'retirada'))
);
CREATE INDEX IF NOT EXISTS idx_portal_propuestas_cliente ON portal_propuestas(tenant_id, cliente_fiscal_id, creada_en);
CREATE INDEX IF NOT EXISTS idx_portal_propuestas_estado ON portal_propuestas(tenant_id, estado);

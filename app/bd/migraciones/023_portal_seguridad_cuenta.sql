-- Portal: seguridad de la cuenta, lectura previa de facturas peticiones de documentos y valoraciones; backoffice: cuotas por despacho y cadena de integridad de su auditoría
ALTER TABLE backoffice.auditoria ADD COLUMN IF NOT EXISTS hash_previo text;
ALTER TABLE backoffice.auditoria ADD COLUMN IF NOT EXISTS hash text;
CREATE TABLE IF NOT EXISTS backoffice.cuotas_despacho (
    tenant_id bigint PRIMARY KEY,
    almacenamiento_mb bigint,
    facturas_mes bigint,
    actualizado_en text NOT NULL,
    actualizado_por text
);
GRANT SELECT, INSERT, UPDATE, DELETE ON backoffice.cuotas_despacho TO guilda_backoffice;
ALTER TABLE portal_recordatorios_config ADD COLUMN IF NOT EXISTS lectura_previa bigint NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS portal_segundo_factor (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    email text NOT NULL,
    secreto text NOT NULL,
    activo bigint NOT NULL DEFAULT 0,
    ultimo_paso bigint NOT NULL DEFAULT 0,
    recuperacion text NOT NULL DEFAULT '[]',
    creado_en text NOT NULL,
    activado_en text,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_portal_segundo_factor ON portal_segundo_factor(tenant_id, email);
CREATE TABLE IF NOT EXISTS portal_sesiones (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    email text NOT NULL,
    sid_hash text NOT NULL,
    dispositivo text NOT NULL DEFAULT '',
    ip text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    ultimo_uso_en text NOT NULL,
    revocada_en text,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_portal_sesiones_persona ON portal_sesiones(tenant_id, email, revocada_en);
CREATE UNIQUE INDEX IF NOT EXISTS idx_portal_sesiones_sid ON portal_sesiones(tenant_id, sid_hash);
CREATE TABLE IF NOT EXISTS portal_peticiones (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    titulo text NOT NULL,
    descripcion text NOT NULL DEFAULT '',
    fecha_limite text,
    estado text NOT NULL DEFAULT 'pendiente',
    nota text NOT NULL DEFAULT '',
    creado_por bigint,
    creado_en text NOT NULL,
    enviada_en text,
    revisada_en text,
    revisada_por bigint,
    PRIMARY KEY (id),
    CHECK (estado IN ('pendiente', 'enviada', 'revisada', 'cancelada'))
);
CREATE INDEX IF NOT EXISTS idx_portal_peticiones_cliente ON portal_peticiones(tenant_id, cliente_fiscal_id, estado);
CREATE TABLE IF NOT EXISTS portal_peticiones_documentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    peticion_id bigint NOT NULL,
    documento_id bigint NOT NULL,
    subido_por text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_portal_peticiones_documentos ON portal_peticiones_documentos(tenant_id, peticion_id, documento_id);
CREATE TABLE IF NOT EXISTS portal_valoraciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    email text NOT NULL,
    tipo text NOT NULL,
    referencia text NOT NULL,
    puntos bigint NOT NULL,
    comentario text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    PRIMARY KEY (id),
    CHECK (puntos BETWEEN 1 AND 5)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_portal_valoraciones ON portal_valoraciones(tenant_id, cliente_fiscal_id, email, tipo, referencia);
CREATE TABLE IF NOT EXISTS salud_silencios (
    clave text,
    asignado_a text,
    silenciado_hasta text,
    motivo text,
    actualizado_por text,
    actualizado_en text NOT NULL,
    PRIMARY KEY (clave)
);

-- Portal: cuestionarios del cliente
CREATE TABLE IF NOT EXISTS portal_cuestionarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    titulo text NOT NULL,
    descripcion text NOT NULL DEFAULT '',
    preguntas text NOT NULL,
    respuestas text,
    estado text NOT NULL DEFAULT 'pendiente',
    fecha_limite text,
    creado_por bigint,
    creado_en text NOT NULL,
    respondido_en text,
    respondido_por text,
    PRIMARY KEY (id),
    CHECK (estado IN ('pendiente', 'respondido', 'recibido', 'cancelado'))
);
CREATE INDEX IF NOT EXISTS idx_portal_cuestionarios_cliente ON portal_cuestionarios(tenant_id, cliente_fiscal_id, estado);

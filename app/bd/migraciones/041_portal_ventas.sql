-- Mis ventas: clientes y facturas emitidas desde el portal con FacturaScripts
CREATE TABLE IF NOT EXISTS portal_ventas_clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    codcliente text NOT NULL,
    nombre text NOT NULL,
    nif text NOT NULL DEFAULT '',
    email text NOT NULL DEFAULT '',
    creado_en text NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (tenant_id, cliente_fiscal_id, codcliente)
);
CREATE TABLE IF NOT EXISTS portal_ventas_facturas (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    venta_cliente_id bigint NOT NULL,
    idfactura text NOT NULL,
    codigo text NOT NULL DEFAULT '',
    fecha text NOT NULL,
    lineas text NOT NULL,
    neto_centimos bigint NOT NULL DEFAULT 0,
    total_centimos bigint NOT NULL DEFAULT 0,
    creada_por text NOT NULL DEFAULT '',
    creada_en text NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_portal_ventas_facturas ON portal_ventas_facturas(tenant_id, cliente_fiscal_id, creada_en);
ALTER TABLE clientes_fiscales ADD COLUMN IF NOT EXISTS ventas_portal bigint NOT NULL DEFAULT 0;
ALTER TABLE clientes_fiscales ADD COLUMN IF NOT EXISTS facturascripts_idempresa bigint;
ALTER TABLE clientes_fiscales ADD COLUMN IF NOT EXISTS facturascripts_serie text;

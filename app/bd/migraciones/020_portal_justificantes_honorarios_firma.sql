-- Justificantes de movimientos del banco (y tiquets) que el cliente explica desde el portal; honorarios visibles por cliente; firma de documentos enviada desde un vencimiento
ALTER TABLE clientes_fiscales ADD COLUMN IF NOT EXISTS portal_honorarios bigint NOT NULL DEFAULT 0;
ALTER TABLE vencimientos_fiscales ADD COLUMN IF NOT EXISTS documenso_firmado_en text;
CREATE TABLE IF NOT EXISTS justificantes_pendientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id bigint NOT NULL,
    cliente_fiscal_id bigint NOT NULL,
    origen text NOT NULL,
    fecha text NOT NULL,
    importe_centimos bigint NOT NULL,
    concepto text NOT NULL,
    estado text NOT NULL DEFAULT 'pendiente',
    factura_id bigint,
    documento_id bigint,
    comentario text,
    huella text NOT NULL,
    pedido_por bigint,
    creado_en text NOT NULL,
    respondido_en text,
    resuelto_por bigint,
    resuelto_en text,
    PRIMARY KEY (id),
    CHECK (origen IN ('extracto', 'cliente')),
    CHECK (estado IN ('pendiente', 'con_factura', 'tiquet', 'personal', 'no_se', 'resuelto', 'descartado'))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_justificantes_huella ON justificantes_pendientes(tenant_id, cliente_fiscal_id, huella);
CREATE INDEX IF NOT EXISTS idx_justificantes_cliente ON justificantes_pendientes(tenant_id, cliente_fiscal_id, estado);

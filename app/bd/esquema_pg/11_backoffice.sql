-- La base propia del backoffice (antes data/backoffice.db, backoffice/auth.py:SCHEMA) como esquema `backoffice` de la misma base de datos. Escrito a mano.
-- Son 10 tablas de administración de la plataforma (administradores y sus intentos de acceso, auditoría de sus acciones, cobros, notas y seguimiento por despacho…): NO son de ningún
-- despacho, no se distribuyen (quedan en el coordinador) y solo las toca el rol `guilda_backoffice`: ni `guilda_app` ni `guilda_plataforma` tienen acceso.
-- El backoffice se conecta con `search_path = backoffice, public`, así que su código las nombra sin esquema, como antes.
CREATE SCHEMA IF NOT EXISTS backoffice;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'guilda_backoffice') THEN
        CREATE ROLE guilda_backoffice LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS backoffice.admins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario text NOT NULL UNIQUE,
    nombre text NOT NULL,
    password_hash text NOT NULL,
    activo bigint NOT NULL DEFAULT 1,
    creado_en text NOT NULL,
    ultimo_acceso text,
    totp_secreto text,
    totp_activo bigint NOT NULL DEFAULT 0,
    totp_ultimo_paso bigint NOT NULL DEFAULT 0,
    codigos_recuperacion text,
    password_cambiada_en text
);
CREATE TABLE IF NOT EXISTS backoffice.intentos_login (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario text NOT NULL,
    ip text NOT NULL,
    creado_en text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_intentos_login ON backoffice.intentos_login (usuario, creado_en);
CREATE TABLE IF NOT EXISTS backoffice.auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id bigint,
    admin_usuario text,
    accion text NOT NULL,
    detalle text,
    ip text,
    creado_en text NOT NULL
);
CREATE TABLE IF NOT EXISTS backoffice.cobros (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    concepto text NOT NULL,
    importe_centimos bigint NOT NULL,
    stripe_session_id text NOT NULL,
    url text NOT NULL,
    estado text NOT NULL DEFAULT 'pendiente',
    admin_usuario text,
    creado_en text NOT NULL,
    actualizado_en text
);
CREATE INDEX IF NOT EXISTS idx_cobros_tenant ON backoffice.cobros (tenant_id);
CREATE TABLE IF NOT EXISTS backoffice.notas_tenant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    texto text NOT NULL,
    admin_usuario text,
    creado_en text NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notas_tenant ON backoffice.notas_tenant (tenant_id);
CREATE TABLE IF NOT EXISTS backoffice.snapshots_tenants (
    fecha text NOT NULL,
    tenant_id bigint NOT NULL,
    plan_id bigint,
    precio_centimos bigint NOT NULL DEFAULT 0,
    activo bigint NOT NULL DEFAULT 1,
    suscripcion_estado text,
    PRIMARY KEY (fecha, tenant_id)
);
CREATE TABLE IF NOT EXISTS backoffice.salud_historial (
    fecha text NOT NULL,
    tenant_id bigint NOT NULL,
    puntos bigint,
    nivel text NOT NULL,
    PRIMARY KEY (fecha, tenant_id)
);
CREATE TABLE IF NOT EXISTS backoffice.seguimiento_tenant (
    tenant_id bigint PRIMARY KEY,
    ultimo_contacto text,
    posponer_hasta text,
    admin_usuario text,
    actualizado_en text
);
CREATE TABLE IF NOT EXISTS backoffice.auditorias_dependencias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha text NOT NULL,
    resultado text NOT NULL
);
CREATE TABLE IF NOT EXISTS backoffice.resumenes_enviados (
    clave text PRIMARY KEY,
    enviado_en text NOT NULL
);

REVOKE ALL ON SCHEMA backoffice FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA backoffice FROM PUBLIC;
GRANT USAGE ON SCHEMA backoffice TO guilda_backoffice;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA backoffice TO guilda_backoffice;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA backoffice TO guilda_backoffice;
ALTER DEFAULT PRIVILEGES IN SCHEMA backoffice GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO guilda_backoffice;
-- el backoffice lee de la base de la aplicación solo lo que ya lee por el rol de la plataforma; aquí no tiene acceso a ninguna tabla de despachos
-- (la auditoría de las acciones del backoffice es de solo anexado: ni se modifica ni se borra)
REVOKE UPDATE, DELETE ON backoffice.auditoria FROM guilda_backoffice;

"""La capa de PostgreSQL contra un servidor DE VERDAD (instancia de ensayo, fase 2).

Se salta si no hay `psycopg`/`psycopg_pool` o si no se indica el servidor:

    GUILDA_TEST_PG_URL=postgresql://guilda:ensayo@127.0.0.1:55432/postgres  pytest tests/test_bd_postgres_real.py

Crea y borra sus propias tablas y roles (nombres con sufijo aleatorio).
"""
import os
import uuid

import pytest

psycopg = pytest.importorskip("psycopg")
pytest.importorskip("psycopg_pool")

URL = os.environ.get("GUILDA_TEST_PG_URL", "")
pytestmark = pytest.mark.skipif(not URL, reason="sin GUILDA_TEST_PG_URL (instancia de ensayo de PostgreSQL)")

from app import bd  # noqa: E402
from app.bd import postgres as pg  # noqa: E402


@pytest.fixture
def pgdb():
    pg.fijar_url(URL)
    sufijo = uuid.uuid4().hex[:8]
    creados = {"tablas": [], "roles": []}
    yield sufijo, creados
    pg.cerrar_pool()
    pg.fijar_url(URL)
    conn = pg.conectar()
    try:
        conn.execute("RESET ROLE")
        for t in creados["tablas"]:
            conn.execute(f"DROP TABLE IF EXISTS {t} CASCADE")
        for r in creados["roles"]:
            conn.execute(f"DROP OWNED BY {r}")
            conn.execute(f"DROP ROLE IF EXISTS {r}")
        conn.commit()
    finally:
        conn.close()
        pg.fijar_url(None)


def test_lastrowid_con_clave_compuesta_e_identidad(pgdb):
    sufijo, creados = pgdb
    t = f"t_{sufijo}"
    creados["tablas"].append(t)
    conn = pg.conectar()
    conn.executescript(f"CREATE TABLE {t} (tenant_id bigint NOT NULL, id bigint GENERATED BY DEFAULT AS IDENTITY, a text UNIQUE, PRIMARY KEY (tenant_id, id))")
    c1 = conn.execute(f"INSERT INTO {t} (tenant_id, a) VALUES (?, ?)", (1, "x"))
    c2 = conn.execute(f"INSERT INTO {t} (tenant_id, a) VALUES (?, ?)", (1, "y"))
    assert isinstance(c1.lastrowid, int) and c2.lastrowid == c1.lastrowid + 1
    conn.commit()
    fila = conn.execute(f"SELECT id, a FROM {t} WHERE a = ?", ("y",)).fetchone()
    assert fila["id"] == c2.lastrowid and fila[1] == "y" and dict(fila) == {"id": c2.lastrowid, "a": "y"}
    conn.close()


def test_error_de_integridad_no_invalida_la_transaccion(pgdb):
    sufijo, creados = pgdb
    t = f"t_{sufijo}"
    creados["tablas"].append(t)
    conn = pg.conectar()
    conn.executescript(f"CREATE TABLE {t} (id bigint PRIMARY KEY, a text UNIQUE)")
    conn.execute(f"INSERT INTO {t} VALUES (1, 'x')")
    with pytest.raises(bd.ErrorIntegridad):
        conn.execute(f"INSERT INTO {t} VALUES (2, 'x')")
    conn.execute(f"INSERT INTO {t} VALUES (3, 'z')")             # la transacción sigue viva
    assert conn.execute(f"UPDATE {t} SET a = 'q' WHERE id = ?", (3,)).rowcount == 1
    conn.commit()
    assert conn.execute(f"SELECT count(*) AS n FROM {t}").fetchone()["n"] == 2
    conn.execute(f"INSERT OR IGNORE INTO {t} VALUES (1, 'otra')")      # traducido a ON CONFLICT DO NOTHING
    conn.commit()
    assert conn.execute(f"SELECT a FROM {t} WHERE id = 1").fetchone()["a"] == "x"
    conn.close()


def test_begin_immediate_nombrados_y_table_info(pgdb):
    sufijo, creados = pgdb
    t = f"t_{sufijo}"
    creados["tablas"].append(t)
    conn = pg.conectar()
    conn.executescript(f"CREATE TABLE {t} (id bigint PRIMARY KEY, a text NOT NULL)")
    conn.execute("BEGIN IMMEDIATE")
    conn.execute(f"INSERT INTO {t} (id, a) VALUES (:id, :a)", {"id": 1, "a": "uno"})
    conn.commit()
    cols = {f["name"]: f for f in conn.execute(f"PRAGMA table_info({t})")}
    assert set(cols) == {"id", "a"} and cols["id"]["pk"] == 1 and cols["a"]["notnull"] == 1
    assert conn.execute(f"SELECT a FROM {t} WHERE a LIKE '%no'").fetchone()["a"] == "uno"
    conn.close()


def test_rls_con_despacho_por_transaccion(pgdb):
    sufijo, creados = pgdb
    t, rol = f"t_{sufijo}", f"rol_{sufijo}"
    creados["tablas"].append(t)
    creados["roles"].append(rol)
    admin = pg.conectar()
    admin.executescript(
        f"CREATE TABLE {t} (tenant_id bigint NOT NULL, id bigint GENERATED BY DEFAULT AS IDENTITY, a text, PRIMARY KEY (tenant_id, id));"
        f"CREATE ROLE {rol} LOGIN;"
        f"GRANT SELECT, INSERT, UPDATE ON {t} TO {rol};"
        f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;"
        f"CREATE POLICY aislamiento ON {t} USING (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint) "
        f"WITH CHECK (tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)"
    )
    admin.execute(f"INSERT INTO {t} (tenant_id, a) VALUES (1, 'a1'), (1, 'a2'), (2, 'b1')")
    admin.commit()
    admin.close()

    def como_app(despacho):
        c = pg.conectar(despacho)
        c.execute(f"SET ROLE {rol}")
        return c

    uno = como_app(1)
    assert uno.execute(f"SELECT count(*) AS n FROM {t}").fetchone()["n"] == 2          # lectura fuera de transacción también va con contexto
    with pytest.raises(bd.ErrorBD):
        uno.execute(f"INSERT INTO {t} (tenant_id, a) VALUES (2, 'intruso')")              # escribir en otro despacho viola la política
    uno.execute(f"INSERT INTO {t} (tenant_id, a) VALUES (1, 'a3')")                       # la transacción sigue viva
    uno.commit()
    assert uno.execute(f"SELECT count(*) AS n FROM {t}").fetchone()["n"] == 3
    uno.execute("RESET ROLE")
    uno.close()
    dos = como_app(2)
    assert dos.execute(f"SELECT count(*) AS n FROM {t}").fetchone()["n"] == 1
    dos.execute("RESET ROLE")
    dos.close()
    nadie = como_app(None)
    assert nadie.execute(f"SELECT count(*) AS n FROM {t}").fetchone()["n"] == 0          # sin contexto: nada (fallo seguro)
    nadie.execute("RESET ROLE")
    nadie.close()

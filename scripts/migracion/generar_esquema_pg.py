#!/usr/bin/env python3
"""Genera el esquema de PostgreSQL a partir del esquema FINAL de SQLite (fase 4 de la migración).

Lee una base de datos SQLite creada por `init_db()` (nunca la de producción) y escribe en
`app/bd/esquema_pg/` los ficheros 01_tablas.sql, 02_indices.sql, 03_claves_foraneas.sql y
04_vistas.sql. Las funciones (00) y los triggers (05) son manuales. tests/test_esquema_pg.py
comprueba que los ficheros del repositorio coinciden con lo que este script genera.

    python scripts/migracion/generar_esquema_pg.py BASE.db [--salida DIRECTORIO]

Decisiones (ver docs/adr-postgresql-citus.md): INTEGER→bigint, TEXT→text, REAL→double precision,
BLOB→bytea; fechas y banderas se quedan como texto ISO y enteros 0/1; `id INTEGER PRIMARY KEY`→identidad;
las claves foráneas van aparte (se añaden tras crear todas las tablas, como exige Citus: D9).
"""
import hashlib
import re
import sqlite3
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
SALIDA = RAIZ / "app" / "bd" / "esquema_pg"
CABECERA = "-- GENERADO por scripts/migracion/generar_esquema_pg.py a partir del esquema de SQLite. No editar a mano.\n"
TIPOS = {"INTEGER": "bigint", "TEXT": "text", "REAL": "double precision", "BLOB": "bytea", "NUMERIC": "numeric"}


class EsquemaNoSoportado(Exception):
    pass


def _comillas(sql, i):
    """Índice del final del literal/identificador entrecomillado que empieza en i."""
    c = sql[i]
    j = i + 1
    while j < len(sql):
        if sql[j] == c:
            if j + 1 < len(sql) and sql[j + 1] == c:
                j += 2
                continue
            return j
        j += 1
    return len(sql) - 1


def extraer_checks(sql):
    """Expresiones de los CHECK (…) de un CREATE TABLE, en orden de aparición."""
    res, i, n = [], 0, len(sql)
    while i < n:
        c = sql[i]
        if c in "'\"":
            i = _comillas(sql, i) + 1
        elif sql.startswith("--", i):
            i = sql.find("\n", i)
            i = n if i < 0 else i
        elif re.match(r"CHECK\s*\(", sql[i:], re.I) and (i == 0 or not (sql[i - 1].isalnum() or sql[i - 1] == "_")):
            j = sql.index("(", i)
            prof, k = 1, j + 1
            while prof:
                if sql[k] in "'\"":
                    k = _comillas(sql, k)
                elif sql[k] == "(":
                    prof += 1
                elif sql[k] == ")":
                    prof -= 1
                k += 1
            res.append(" ".join(sql[j + 1:k - 1].split()))
            i = k
        else:
            i += 1
    return res


def _defecto(valor, tabla, columna):
    v = valor.strip()
    while v.startswith("(") and v.endswith(")") and v.count("(") == v.count(")"):
        v = v[1:-1].strip()
    if re.fullmatch(r"datetime\(\s*'now'\s*,\s*'localtime'\s*\)", v, re.I):
        return "to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')"            # la base de datos usa timezone Europe/Madrid
    if re.search(r"\b(datetime|date|strftime|julianday|CURRENT_TIMESTAMP|CURRENT_DATE|random)\b", v, re.I):
        raise EsquemaNoSoportado(f"DEFAULT {v!r} en {tabla}.{columna}: traducir a mano")
    return v


def _nombre_fk(tabla, columnas):
    n = f"fk_{tabla}_{'_'.join(columnas)}"
    return n if len(n) <= 60 else n[:50] + "_" + hashlib.sha1(n.encode()).hexdigest()[:8]


def generar(ruta_sqlite):
    con = sqlite3.connect(f"file:{ruta_sqlite}?mode=ro", uri=True)
    maestro = con.execute("SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY name").fetchall()
    virtuales = {n for t, n, _, s in maestro if t == "table" and (s or "").upper().startswith("CREATE VIRTUAL")}
    sombras = tuple(v + "_" for v in virtuales)
    tablas = [n for t, n, _, s in maestro if t == "table" and not n.startswith("sqlite_") and n not in virtuales and not n.startswith(sombras)]
    sql_de = {n: s for t, n, _, s in maestro if t == "table"}
    ddl, fks, avisos = [], [], []
    for t in tablas:
        cols = con.execute(f'PRAGMA table_info("{t}")').fetchall()
        pk = [c[1] for c in sorted((c for c in cols if c[5]), key=lambda c: c[5])]
        identidad = len(pk) == 1 and pk[0] == "id" and next(c for c in cols if c[1] == "id")[2].upper() == "INTEGER"
        if len(pk) == 1 and not identidad and not pk[0].endswith("_id") and next(c for c in cols if c[1] == pk[0])[2].upper() == "INTEGER":
            avisos.append(f"{t}.{pk[0]}: INTEGER PRIMARY KEY que no se llama id (alias de rowid en SQLite): se crea SIN identidad")
        lineas = []
        for _, nombre, tipo, nonulo, defecto, _pk in cols:
            tipo_pg = TIPOS.get((tipo or "").upper().split("(")[0])
            if tipo_pg is None:
                raise EsquemaNoSoportado(f"tipo {tipo!r} en {t}.{nombre}")
            partes = [nombre, tipo_pg]
            if identidad and nombre == "id":
                partes.append("GENERATED BY DEFAULT AS IDENTITY")
            elif nonulo and nombre not in pk:
                partes.append("NOT NULL")
            if defecto is not None and not (identidad and nombre == "id"):
                partes.append("DEFAULT " + _defecto(defecto, t, nombre))
            lineas.append("    " + " ".join(partes))
        if pk:
            lineas.append(f"    PRIMARY KEY ({', '.join(pk)})")
        vistos = set()
        for fila in con.execute(f'PRAGMA index_list("{t}")').fetchall():
            if fila[3] == "u":                                                         # restricción UNIQUE de la tabla
                columnas = tuple(r[2] for r in sorted(con.execute(f'PRAGMA index_info("{fila[1]}")').fetchall()))
                if columnas not in vistos:
                    vistos.add(columnas)
                    lineas.append(f"    UNIQUE ({', '.join(columnas)})")
        for chk in extraer_checks(sql_de[t]):
            lineas.append(f"    CHECK ({chk})")
        ddl.append(f"CREATE TABLE IF NOT EXISTS {t} (\n" + ",\n".join(lineas) + "\n);\n")
        grupos = {}
        for f in con.execute(f'PRAGMA foreign_key_list("{t}")').fetchall():
            grupos.setdefault(f[0], []).append(f)
        for _id, filas in sorted(grupos.items()):
            filas.sort(key=lambda f: f[1])
            origen = [f[3] for f in filas]
            padre = filas[0][2]
            destino = [f[4] for f in filas]
            if any(d is None for d in destino):                                         # referencia a la clave primaria del padre
                destino = [c[1] for c in sorted((c for c in con.execute(f'PRAGMA table_info("{padre}")').fetchall() if c[5]), key=lambda c: c[5])]
            accion = ""
            if filas[0][6] not in ("NO ACTION", None):
                accion += f" ON DELETE {filas[0][6]}"
            if filas[0][5] not in ("NO ACTION", None):
                accion += f" ON UPDATE {filas[0][5]}"
            fks.append((t, _nombre_fk(t, origen), f"ALTER TABLE {t} ADD CONSTRAINT {_nombre_fk(t, origen)} FOREIGN KEY ({', '.join(origen)}) "
                                                f"REFERENCES {padre} ({', '.join(destino)}){accion};"))
    indices = []
    for t, n, tbl, s in maestro:
        if t == "index" and s and tbl in tablas:
            s2 = re.sub(r"^\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(IF\s+NOT\s+EXISTS\s+)?", lambda m: "CREATE " + (m.group(1) or "") + "INDEX IF NOT EXISTS ", s, flags=re.I)
            indices.append(" ".join(s2.split()) + ";")
    vistas = [f"CREATE OR REPLACE VIEW {n} AS\n" + re.sub(r"^\s*CREATE\s+VIEW\s+\S+\s+AS\s*", "", s, flags=re.I).strip() + ";\n" for t, n, _, s in maestro if t == "view"]
    return {
        "01_tablas.sql": CABECERA + "\n".join(ddl),
        "02_indices.sql": CABECERA + "\n".join(sorted(indices)) + "\n",
        "03_claves_foraneas.sql": CABECERA + "\n".join(x[2] for x in sorted(fks)) + "\n",
        "04_vistas.sql": CABECERA + "\n".join(vistas),
    }, avisos


# --- Variante multitenant (fase 6b): lo que necesita Citus ------------------------------------------------------------------------------------------
CONTEXTO_TENANT = "nullif(current_setting('app.tenant_id', true), '')::bigint"
SALIDA_MT = RAIZ / "app" / "bd" / "esquema_pg" / "mt"


def generar_multitenant(ruta_sqlite, modelo=None):
    """Esquema con `tenant_id` en toda tabla de un despacho, claves primarias, UNIQUE y claves foráneas compuestas, y los guiones de distribución y de RLS.

    * tablas distribuidas (propio/hija/usuario): `tenant_id bigint NOT NULL DEFAULT <despacho de la conexión>`, PK `(tenant_id, …)`, todo UNIQUE con `tenant_id` delante.
    * tablas de referencia: sin cambios. Locales: sin cambios.
    * claves foráneas: distribuida→distribuida son compuestas `(tenant_id, col)`; hacia referencia, normales; `ON DELETE SET NULL` solo anula la columna (PostgreSQL ≥ 15).
    """
    import json
    if modelo is None:
        modelo = json.loads((RAIZ / "app" / "bd" / "tenant_modelo.json").read_text(encoding="utf-8"))
    clase = {t: v["clase"] for t, v in modelo.items()}
    dist = sorted(t for t, c in clase.items() if c in ("propio", "hija", "usuario"))
    refs = sorted(t for t, c in clase.items() if c == "referencia")
    con = sqlite3.connect(f"file:{ruta_sqlite}?mode=ro", uri=True)
    maestro = con.execute("SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY name").fetchall()
    sql_de = {n: s for t, n, _, s in maestro if t == "table"}
    ddl, fks, avisos = [], [], []
    anulan = {}                                                      # padre -> [(hija, columna, clave del padre)]: ON DELETE SET NULL entre tablas distribuidas
    for t in sorted(clase):
        if t not in sql_de:
            continue
        cols = con.execute(f'PRAGMA table_info("{t}")').fetchall()
        pk = [c[1] for c in sorted((c for c in cols if c[5]), key=lambda c: c[5])]
        es_dist = t in dist
        identidad = len(pk) == 1 and pk[0] == "id" and next(c for c in cols if c[1] == "id")[2].upper() == "INTEGER"
        lineas = []
        for _, nombre, tipo, nonulo, defecto, _pk in cols:
            tipo_pg = TIPOS[(tipo or "").upper().split("(")[0]]
            if es_dist and nombre == "tenant_id":
                lineas.append(f"    tenant_id bigint NOT NULL DEFAULT {CONTEXTO_TENANT}")
                continue
            partes = [nombre, tipo_pg]
            if identidad and nombre == "id":
                partes.append("GENERATED BY DEFAULT AS IDENTITY")
            elif nonulo and nombre not in pk:
                partes.append("NOT NULL")
            if defecto is not None and not (identidad and nombre == "id"):
                partes.append("DEFAULT " + _defecto(defecto, t, nombre))
            lineas.append("    " + " ".join(partes))
        if es_dist and not any(c[1] == "tenant_id" for c in cols):
            lineas.append(f"    tenant_id bigint NOT NULL DEFAULT {CONTEXTO_TENANT}")
        pk_pg = (["tenant_id"] + [c for c in pk if c != "tenant_id"]) if es_dist and pk else pk
        if pk_pg:
            lineas.append(f"    PRIMARY KEY ({', '.join(pk_pg)})")
        vistos = set()
        for fila in con.execute(f'PRAGMA index_list("{t}")').fetchall():
            if fila[3] == "u":
                columnas = tuple(r[2] for r in sorted(con.execute(f'PRAGMA index_info("{fila[1]}")').fetchall()))
                if es_dist and "tenant_id" not in columnas:
                    columnas = ("tenant_id",) + columnas
                if columnas not in vistos and columnas != tuple(pk_pg):
                    vistos.add(columnas)
                    lineas.append(f"    UNIQUE ({', '.join(columnas)})")
        for chk in extraer_checks(sql_de[t]):
            lineas.append(f"    CHECK ({chk})")
        ddl.append(f"CREATE TABLE IF NOT EXISTS {t} (\n" + ",\n".join(lineas) + "\n);\n")
        grupos = {}
        for f in con.execute(f'PRAGMA foreign_key_list("{t}")').fetchall():
            grupos.setdefault(f[0], []).append(f)
        ya_apunta_a_tenants = any(len(fs) == 1 and fs[0][3] == "tenant_id" and fs[0][2] == "tenants" for fs in grupos.values())
        if es_dist and not ya_apunta_a_tenants:
            fks.append((t, f"fk_{t}_tenant", f"ALTER TABLE {t} ADD CONSTRAINT fk_{t}_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id);"))
        for _id, filas in sorted(grupos.items()):
            filas.sort(key=lambda f: f[1])
            origen, padre = [f[3] for f in filas], filas[0][2]
            if padre not in clase:
                continue
            destino = [f[4] for f in filas]
            if any(d is None for d in destino):
                destino = [c[1] for c in sorted((c for c in con.execute(f'PRAGMA table_info("{padre}")').fetchall() if c[5]), key=lambda c: c[5])]
            borrar = filas[0][6] if filas[0][6] not in ("NO ACTION", None) else ""
            actualizar = filas[0][5] if filas[0][5] not in ("NO ACTION", None) else ""
            if clase[t] in ("propio", "hija", "usuario") and clase[padre] in ("propio", "hija", "usuario"):
                if "tenant_id" in origen and "tenant_id" in destino:
                    pass
                cols_o, cols_d = ["tenant_id"] + origen, ["tenant_id"] + destino
                accion = ""
                if borrar == "SET NULL":
                    # Citus no admite SET NULL si la clave foránea incluye la columna de distribución: lo hace un trigger BEFORE DELETE del padre (misma colocación, mismo shard)
                    if len(origen) != 1:
                        raise EsquemaNoSoportado(f"{t}: ON DELETE SET NULL con varias columnas")
                    anulan.setdefault(padre, []).append((t, origen[0], destino[0]))
                elif borrar:
                    accion += f" ON DELETE {borrar}"
                if actualizar:
                    accion += f" ON UPDATE {actualizar}"
                fks.append((t, _nombre_fk(t, origen), f"ALTER TABLE {t} ADD CONSTRAINT {_nombre_fk(t, origen)} FOREIGN KEY ({', '.join(cols_o)}) REFERENCES {padre} ({', '.join(cols_d)}){accion};"))
            elif clase[padre] == "local" and clase[t] != "local":
                avisos.append(f"{t}.{origen} → {padre}: clave foránea hacia una tabla local; no se crea")
            elif clase[t] == "referencia" and clase[padre] in ("propio", "hija", "usuario"):
                avisos.append(f"{t}.{origen} → {padre}: una tabla de referencia no puede apuntar a una distribuida; no se crea")
            else:
                accion = (f" ON DELETE {borrar}" if borrar else "") + (f" ON UPDATE {actualizar}" if actualizar else "")
                fks.append((t, _nombre_fk(t, origen), f"ALTER TABLE {t} ADD CONSTRAINT {_nombre_fk(t, origen)} FOREIGN KEY ({', '.join(origen)}) REFERENCES {padre} ({', '.join(destino)}){accion};"))
    indices = []
    for t, n, tbl, sql in maestro:
        if t == "index" and sql and tbl in clase:
            m = re.match(r"^\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\S+)\s+ON\s+(\S+?)\s*\((.*?)\)\s*(WHERE.*)?$", " ".join(sql.split()), re.I | re.S)
            if not m:
                raise EsquemaNoSoportado(f"índice no reconocido: {sql[:80]}")
            unico, nombre, tabla, columnas, donde = m.groups()
            if unico and tabla in dist and not re.search(r"\btenant_id\b", columnas):
                columnas = "tenant_id, " + columnas
            indices.append(f"CREATE {'UNIQUE ' if unico else ''}INDEX IF NOT EXISTS {nombre} ON {tabla} ({columnas}){' ' + donde if donde else ''};")
    primera = dist[0]
    distribuir = ["-- Citus: tablas de referencia (replicadas en cada nodo) y tablas distribuidas por tenant_id, todas colocalizadas. Generado.", ""]
    distribuir += [f"SELECT create_reference_table('{t}');" for t in (["tenants"] + [r for r in refs if r != "tenants"])]
    distribuir += ["", f"SELECT create_distributed_table('{primera}', 'tenant_id');"]
    distribuir += [f"SELECT create_distributed_table('{t}', 'tenant_id', colocate_with => '{primera}');" for t in dist[1:]]
    rls = ["-- RLS: cada fila de una tabla distribuida solo la ve y la escribe la conexión cuyo despacho (app.tenant_id) es el suyo. Generado.", ""]
    for t in dist:
        rls.append(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;")
        rls.append(f"DROP POLICY IF EXISTS aislamiento ON {t};")
        rls.append(f"CREATE POLICY aislamiento ON {t} USING (tenant_id = {CONTEXTO_TENANT}) WITH CHECK (tenant_id = {CONTEXTO_TENANT});")
    vistas = [f"CREATE OR REPLACE VIEW {n} AS\n" + re.sub(r"^\s*CREATE\s+VIEW\s+\S+\s+AS\s*", "", sql, flags=re.I).strip() + ";\n" for t, n, _, sql in maestro if t == "view"]
    set_null = ["-- ON DELETE SET NULL entre tablas distribuidas, como triggers (Citus no lo admite en claves foráneas que incluyen tenant_id). Generado.", ""]
    for padre, hijas in sorted(anulan.items()):
        cuerpo = "\n".join(f"    UPDATE {h} SET {c} = NULL WHERE tenant_id = OLD.tenant_id AND {c} = OLD.{k};" for h, c, k in sorted(hijas))
        set_null.append(f"CREATE OR REPLACE FUNCTION fk_set_null_{padre}() RETURNS trigger LANGUAGE plpgsql AS $$\nBEGIN\n{cuerpo}\n    RETURN OLD;\nEND $$;")
        set_null.append(f"DROP TRIGGER IF EXISTS fk_set_null ON {padre};")
        set_null.append(f"CREATE TRIGGER fk_set_null BEFORE DELETE ON {padre} FOR EACH ROW EXECUTE FUNCTION fk_set_null_{padre}();\n")
    return {
        "01_tablas.sql": CABECERA + "\n".join(ddl),
        "02_indices.sql": CABECERA + "\n".join(sorted(indices)) + "\n",
        "03_claves_foraneas.sql": CABECERA + "\n".join(x[2] for x in sorted(fks)) + "\n",
        "04_vistas.sql": CABECERA + "\n".join(vistas),
        "05b_set_null.sql": CABECERA + "\n".join(set_null) + "\n",
        "08_distribuir.sql": CABECERA + "\n".join(distribuir) + "\n",
        "09_rls.sql": CABECERA + "\n".join(rls) + "\n",
    }, avisos


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    mt = "--multitenant" in sys.argv
    salida = Path(sys.argv[sys.argv.index("--salida") + 1]) if "--salida" in sys.argv else (SALIDA_MT if mt else SALIDA)
    ficheros, avisos = (generar_multitenant if mt else generar)(sys.argv[1])
    salida.mkdir(parents=True, exist_ok=True)
    for nombre, texto in ficheros.items():
        (salida / nombre).write_text(texto, encoding="utf-8")
        print(f"{nombre}: {texto.count(chr(10))} líneas")
    for a in avisos:
        print("AVISO:", a)
